class MOEADTensor(MultiObjectiveOptimizer, TensorizedMultiObjectiveOptimizer):
    """
        Tensorized implementation of MOEA/D
        based on the following work:
        Z. Liang, H. Li, N. Yu, K. Sun and R. Cheng, "Bridging Evolutionary Multiobjective Optimization and GPU Acceleration via Tensorization,"
        in IEEE Transactions on Evolutionary Computation, vol. 30, no. 1, pp. 420-434, Feb. 2026, doi: 10.1109/TEVC.2025.3555605.
    """

    def __init__(
        self,
        params: Optional[Dict[str, Any]] = None,
        crossover_operator=None,
        mutation_operator=None,
        weight_vectors=None,
        decomposition_method: _BaseAggregation =  None,
        **kwargs
    ) -> None:
        """Initialization method."""
        logger.info("Overriding class: Optimizer -> MOEAD (Tensor).")

        super().__init__()

        self.n_subproblems = None
        self.neighborhood_size = None
        self.crossover_operator = crossover_operator or SBXCrossoverTensor(env=Environment('numpy', 'float32'))
        self.mutation_operator = mutation_operator or PolynomialMutationTensor(env=Environment('numpy', 'float32'))
        self.decomposition_method = decomposition_method or PBI()
        self.weight_vectors = weight_vectors

        self.build(params)

        logger.info("Class overrided.")

    @property
    def n_subproblems(self) -> int:
        return self._n_subproblems

    @n_subproblems.setter
    def n_subproblems(self, n_subproblems: Optional[int]) -> None:
        if n_subproblems is not None:
            if not isinstance(n_subproblems, int):
                raise TypeError("`n_subproblems` should be an integer.")
            if n_subproblems <= 0:
                raise ValueError("`n_subproblems` should be higher than 0.")
        self._n_subproblems = n_subproblems

    @property
    def neighborhood_size(self) -> int:
        return self._neighborhood_size

    @neighborhood_size.setter
    def neighborhood_size(self, neighborhood_size: Optional[int]) -> None:
        if neighborhood_size is not None:
            if not isinstance(neighborhood_size, int):
                raise TypeError("`neighborhood_size` should be an integer.")
            if neighborhood_size < 2:
                raise ValueError("`neighborhood_size` should be higher than 1.")
        self._neighborhood_size = neighborhood_size

    @property
    def T(self) -> Any:
        return self._T
        
    @T.setter
    def T(self, T: Any) -> None:
        self._T = T

    @property
    def weight_vectors(self) -> Any:
        return self._weight_vectors

    @weight_vectors.setter
    def weight_vectors(self, weights: Any) -> None:
        self._weight_vectors = weights

    @property
    def z(self) -> Any:
        return self._z

    @z.setter
    def z(self, ref: Any) -> None:
        self._z = ref

    def compile(self, space: _MultiObjectiveTensorSpace, **kwargs) -> None:
        """Compiles additional information that is used by this optimizer."""
        if self.n_subproblems is None:
            self.n_subproblems = space.n_agents

        if self.neighborhood_size is None:
            self.neighborhood_size = max(2, int(space.env.xp.ceil(self.n_subproblems * 0.2)))

        self.weight_vectors = space.env.xp.array(self.weight_vectors)
        self.crossover_operator.env = space.env
        self.mutation_operator.env = space.env

        self._build_neighborhood(space.env.xp)

        self.z = space.env.xp.full(space.n_objectives, space.env.xp.inf)

    def _build_neighborhood(self, xp) -> None:
        diff = self.weight_vectors[:, xp.newaxis, :] - self.weight_vectors[xp.newaxis, :, :]
        dist_matrix = xp.sqrt(xp.sum(diff ** 2, axis=2))
        self.T = xp.argsort(dist_matrix, axis=1)[:, :self.neighborhood_size]


    def evaluate(self, space: _MultiObjectiveTensorSpace, function: Function) -> None:
        xp = space.env.xp
        
     
        
        space.F = function(space.X, xp=xp)
            
        self.z = xp.minimum(self.z, xp.min(space.F, axis=0))

        self.evaluate = lambda args: None
           


    def _mating_selection(self, space: _MultiObjectiveTensorSpace) -> Tuple:
        xp = space.env.xp
        
        rand_idx = xp.random.randint(0, self.neighborhood_size, size=(self.n_subproblems, 2))
        rows = xp.arange(self.n_subproblems)[:, xp.newaxis]
        neighbors_idx = self.T[rows, rand_idx] 
        
        parent1_indices = neighbors_idx[:, 0] % space.n_agents
        parent2_indices = neighbors_idx[:, 1] % space.n_agents
        
        
        parents1_X = space.X[parent1_indices]
        parents2_X = space.X[parent2_indices]
        
        return parents1_X, parents2_X

    def update(self, space: _MultiObjectiveTensorSpace, function: Function) -> None:
        xp = space.env.xp

        
        parents1_X, parents2_X = self._mating_selection(space)
        
        
        child1_X, child2_X = self.crossover_operator(parents1_X, parents2_X, space.lb, space.ub)
        del child2_X
        offspring_X = self.mutation_operator(child1_X, space.lb, space.ub) 
        
        
        O = offspring_X[:self.n_subproblems]
        
        F2 = function(O, xp=xp)

        
        self.z = xp.minimum(self.z, xp.min(F2, axis=0))

      
        targets = self.T.flatten() % space.n_agents 
        
        
        O_exp = xp.repeat(O, self.neighborhood_size, axis=0)
        F2_exp = xp.repeat(F2, self.neighborhood_size, axis=0)
        
        
        F_nb = space.F[targets]
        W_nb = self.weight_vectors[targets]
        
        
        g_old = self.decomposition_method(F_nb, W_nb, xp, z=self.z)
        g_new = self.decomposition_method(F2_exp, W_nb, xp, z=self.z)
        
    
        mask = g_new <= g_old
        
       
        valid_targets = targets[mask]
        valid_O = O_exp[mask]
        valid_F2 = F2_exp[mask]
        valid_g_new = g_new[mask]
        
        
        sort_idx = xp.argsort(valid_g_new)
        valid_targets = valid_targets[sort_idx]
        valid_O = valid_O[sort_idx]
        valid_F2 = valid_F2[sort_idx]
        
        _, unique_indices = xp.unique(valid_targets, return_index=True)
        final_targets = valid_targets[unique_indices]
        final_O = valid_O[unique_indices]
        final_F2 = valid_F2[unique_indices]

        space.X[final_targets] = final_O
        space.F[final_targets] = final_F2
        

