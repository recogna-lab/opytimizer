class MOEAD(MultiObjectiveOptimizer):
    """MOEAD class, inherited from Optimizer.

    References:
        Zhang, Q., & Li, H. (2007). MOEA/D: A multiobjective evolutionary algorithm based on decomposition.
        IEEE Transactions on evolutionary computation, 11(6), 712-731.

    """

    def __init__(
        self,
        params: Optional[Dict[str, Any]] = None,
        crossover_operator=None,
        mutation_operator=None,
        weight_vectors=None,
        neighborhood_size: int = None,
        decomposition_method: _BaseAggregation =  None,
        **kwargs
    ) -> None:
        """Initialization method.

        Args:
            params: Contains key-value parameters to the meta-heuristics.
            crossover_operator: Crossover operator to be used.
            mutation_operator: Mutation operator to be used.
            weight_vectors: Weights generated by utils.weight_vectors methods
            decomposition_method: The decomposition method reference (avaliables methods on `utils.math.aggregation`)
            

        """
        logger.info("Overriding class: Optimizer -> MOEAD (Default).")

        super().__init__()

        self.neighborhood_size = neighborhood_size
        self.crossover_operator = crossover_operator or SBXCrossover(n_offspring=1)
        self.mutation_operator = mutation_operator or PolynomialMutation()
        self.decomposition_method = decomposition_method or Tchebycheff()
        self.weight_vectors = weight_vectors

        self.build(params)

        self.T = None # neighborhood index array
    
        logger.info("Class overrided.")



    @property
    def neighborhood_size(self) -> int:
        """Size of neighborhood T."""
        return self._neighborhood_size

    @neighborhood_size.setter
    def neighborhood_size(self, neighborhood_size: Optional[int]) -> None:
        if neighborhood_size is not None:
            if not isinstance(neighborhood_size, int):
                raise e.TypeError("`neighborhood_size` should be an integer.")
            if neighborhood_size < 2:
                raise e.ValueError("`neighborhood_size` should be higher than 1.")

        self._neighborhood_size = neighborhood_size

    @property
    def T(self) -> np.ndarray:
        """Neighborhood of each subproblem."""
        return self._T
    @T.setter
    def T(self, T: np.ndarray) -> None:
        self._T = T
        

    @property
    def weight_vectors(self) -> np.ndarray:
        """Normalized weights vector."""
        return self._weight_vectors

    @weight_vectors.setter
    def weight_vectors(self, weights: np.ndarray) -> None:
        if not isinstance(weights, np.ndarray):
            weights = np.array(weights)
        self._weight_vectors = weights

    @property
    def z(self) -> np.ndarray:
        """Reference point."""
        return self._z

    @z.setter
    def z(self, ref: np.ndarray) -> None:
        if not isinstance(ref, np.ndarray):
            ref = np.array(ref)
        self._z = ref


    
    def _build_neighborhood(self) -> None:
        dists = np.sum(self.weight_vectors**2, axis=1, keepdims=True) - 2 * np.dot(self.weight_vectors, self.weight_vectors.T) + np.sum(self.weight_vectors**2, axis=1)
        dists = np.maximum(dists, 0)
        neighbors = np.argpartition(dists, kth=self.neighborhood_size, axis=1)[:, :self.neighborhood_size]

        rows = np.arange(neighbors.shape[0])[:, None]
        sorted_neighbors = neighbors[rows, np.argsort(dists[rows, neighbors], axis=1)]

        self.T = sorted_neighbors


    def _parents_indices_selection(self, subproblem_index: int) -> Tuple[int, int]:
        """Returns the parents indices"""

        parents_indices = np.random.choice(self.T[subproblem_index], 2, replace=False)
        return parents_indices[0], parents_indices[1]


    def _genetic_operators(self, P1: Agent, P2: Agent) -> Union[Agent, List[Agent]]:
        
        offspring = self.crossover_operator(P1, P2)

        if isinstance(offspring, tuple):
            # two offsprings
            child_1, child_2 = offspring
            child_1, child_2 = self.mutation_operator(child_1[0]), self.mutation_operator(child_2[0])
            return [child_1, child_2]
        else:
            #one offspring
            child_1 = self.mutation_operator(offspring)
            return child_1

    def _environmental_selection(self, children: List[Agent], subproblem_index: int, space: _MultiObjectiveSpace) -> None:
        
        neighbors = self.T[subproblem_index]
        
        weights = self.weight_vectors[neighbors]
        neighbors_fit = np.array([space.agents[idx].fit for idx in neighbors])
        
        current_pop_aggr = self.decomposition_method(neighbors_fit, weights, np, z=self.z)

        children_aggr = np.array([
            self.decomposition_method(child.fit, weights, np, z=self.z) 
            for child in children
        ])

       
        best_child_indices = np.argmin(children_aggr, axis=0)
        best_child_aggr = np.min(children_aggr, axis=0)
        
        replace_mask = best_child_aggr <= current_pop_aggr

        for i, neighbor_index in enumerate(neighbors):
            if replace_mask[i]:
                selected_agent = children[best_child_indices[i]]
                space.agents[neighbor_index].position = selected_agent.position.copy()
                space.agents[neighbor_index].fit = selected_agent.fit.copy()
        
    def compile(self, space: _MultiObjectiveSpace):
        
        if self.neighborhood_size is None: self.neighborhood_size = int(0.2 * space.n_agents)

        self._build_neighborhood()

        self.z = np.full(shape=space.n_objectives, fill_value=np.inf)



    def evaluate(self, space: _MultiObjectiveSpace, function: Function) -> None:
        
        # Initial evaluation -> then this function will be overrided
        for agent in space.agents:
            agent.fit = function(agent.position)
            self.z = np.minimum(self.z, agent.fit)

        

        self.evaluate = lambda : None


    def update(self, space: _MultiObjectiveSpace, function: Function) -> None:
        # main loop
        
        #subproblems permutation -> avoids update bias
        subproblems_order = np.random.permutation(space.n_agents)

        for sub_problem_index in subproblems_order:
            p_1_index, p_2_index = self._parents_indices_selection(sub_problem_index)
            children = self._genetic_operators(space.agents[p_1_index], space.agents[p_2_index])

            fits = []
            for child in children:
                child.fit = function(child.position)
                fits.append(child.fit) 
            
            self.z = np.minimum(self.z, np.min(fits, axis=0))
            
            self._environmental_selection(children, sub_problem_index, space)



